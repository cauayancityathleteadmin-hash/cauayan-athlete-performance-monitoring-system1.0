// Numbered section heading used inside .report-doc (same markup as
// RdSection in pages/reports.js — kept in sync here for new reports).
export function RdSection({ num, title, meta, children }) {
  return (
    <section>
      <div className="rd-section-title"><span className="rd-sec-no">{num}</span>{title}{meta ? <span>{meta}</span> : null}</div>
      {children}
    </section>
  );
}

// Print scoping: only the workspace matching body[data-print-scope] is printed
// (see styles/report-print.css). Set the scope, then open the print dialog.
export function printScope(scope) {
  if (typeof document !== "undefined") document.body.dataset.printScope = scope;
  if (typeof window !== "undefined") window.print();
}
